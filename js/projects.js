function renderProjects() {
    const container = document.querySelector('.projects-base-container');
    const modalsContainer = document.getElementById('projectsModals');
    if (!container || !modalsContainer) return;

    container.innerHTML = '';
    modalsContainer.innerHTML = '';

    projectsData.forEach((project) => {
        const card = document.createElement('div');
        card.className = 'project-container hidden-animation';
        card.setAttribute('data-project-title', project.title.toLowerCase());
        card.innerHTML = `
            <div class="project-image">
                <div class="laptop-container">
                    <img src="${project.image}" alt="${project.title} Project Image" />
                    <div class="laptop-keyboard"></div>
                </div>
            </div>
            <div class="project-info">
                <h2>${project.title}</h2>
                <p>${project.description}</p>
                <button type="button" class="Documents-btn" data-bs-toggle="modal" data-bs-target="#${project.id}Modal">
                    <span class="text">Case Study</span>
                </button>
            </div>
        `;
        container.appendChild(card);

        const modalDescArray = Array.isArray(project.modalDescription)
            ? project.modalDescription
            : [project.modalDescription];
        const modalParagraphs = modalDescArray.map(p => `<p class="text-justify my-3">${p}</p>`).join('');
        const toolsHtml = project.tools.map(tool => `<div><i class="${tool.icon}"></i> ${tool.name}</div>`).join('');
        const isExternal = project.liveUrl.startsWith('http');

        const modal = document.createElement('div');
        modal.className = 'modal fade';
        modal.id = `${project.id}Modal`;
        modal.setAttribute('tabindex', '-1');
        modal.setAttribute('aria-labelledby', `${project.id}ModalLabel`);
        modal.setAttribute('aria-hidden', 'true');
        modal.innerHTML = `
            <div class="modal-dialog modal-lg">
                <div class="modal-content">
                    <div class="modal-header">
                        <h4 class="modal-title text-secondary" id="${project.id}ModalLabel">Case Study</h4>
                        <button type="button" class="btn-close" data-bs-dismiss="modal" aria-label="Close"></button>
                    </div>
                    <div class="modal-body text-center d-flex flex-column align-items-center justify-content-start modal-overflow">
                        <h1 class="fs-1 fw-bold my-2">${project.title}</h1>
                        <div class="project-image">
                            <div class="laptop-container">
                                <img src="${project.image}" alt="${project.title} Project Image" />
                                <div class="laptop-keyboard"></div>
                            </div>
                        </div>
                        <h2 class="my-3">Project Overview</h2>
                        <div class="modal-paragraph">
                            ${modalParagraphs}
                            <div class="project-language">
                                <h2 class="my-3">Tool Used</h2>
                                <div class="language-container">
                                    ${toolsHtml}
                                </div>
                            </div>
                            <div class="link-container">
                                <h2 class="my-3 fs-3">See Live</h2>
                                <a href="${project.liveUrl}" id="visit" class="text-secondary" ${isExternal ? 'target="_blank" rel="noopener noreferrer"' : ''}>
                                    ${project.liveText} <i class="fa-solid fa-up-right-from-square"></i>
                                </a>
                            </div>
                        </div>
                    </div>
                    <div class="modal-footer">
                        <button type="button" class="btn btn-secondary px-3 py-2" data-bs-dismiss="modal">Close</button>
                    </div>
                </div>
            </div>
        `;
        modalsContainer.appendChild(modal);
    });

    initProjectAnimations();
    initProjectPagination();
}

function initProjectAnimations() {
    const elements = document.querySelectorAll('.hidden-animation');
    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('visible-animation');
                observer.unobserve(entry.target);
            }
        });
    });
    elements.forEach(element => observer.observe(element));
}

function initProjectPagination() {
    const searchInput = document.getElementById('projectSearchInput');
    const projectsMeta = document.getElementById('projectsMeta');
    const projectsNoResults = document.getElementById('projectsNoResults');
    const pagination = document.getElementById('projectsPagination');
    const prevBtn = document.getElementById('projectsPrevBtn');
    const nextBtn = document.getElementById('projectsNextBtn');
    const pageInfo = document.getElementById('projectsPageInfo');
    const listContainer = document.querySelector('.projects-base-container');

    if (!searchInput || !projectsMeta || !projectsNoResults || !pagination || !prevBtn || !nextBtn || !pageInfo || !listContainer) return;

    const allProjects = Array.from(listContainer.querySelectorAll('.project-container'));
    if (!allProjects.length) return;

    const itemsPerPage = 2;
    let currentPage = 1;
    let filteredProjects = [...allProjects];

    const clamp = (num, min, max) => Math.min(Math.max(num, min), max);

    function applyFilter() {
        const query = searchInput.value.trim().toLowerCase();
        filteredProjects = allProjects.filter((project) => {
            const title = project.getAttribute('data-project-title') || '';
            const description = project.querySelector('p')?.textContent.toLowerCase() || '';
            return title.includes(query) || description.includes(query);
        });
        currentPage = 1;
        render();
    }

    function render() {
        const totalItems = filteredProjects.length;
        const totalPages = Math.max(1, Math.ceil(totalItems / itemsPerPage));
        currentPage = clamp(currentPage, 1, totalPages);

        const start = (currentPage - 1) * itemsPerPage;
        const end = start + itemsPerPage;
        const visibleProjects = new Set(filteredProjects.slice(start, end));

        allProjects.forEach((project) => {
            project.style.display = visibleProjects.has(project) ? 'flex' : 'none';
        });

        if (!totalItems) {
            projectsMeta.textContent = 'Showing 0 of 0 projects';
            pageInfo.textContent = 'Page 0 of 0';
        } else {
            const startItem = start + 1;
            const endItem = Math.min(end, totalItems);
            projectsMeta.textContent = `Showing ${startItem}-${endItem} of ${totalItems} projects`;
            pageInfo.textContent = `Page ${currentPage} of ${totalPages}`;
        }

        projectsNoResults.classList.toggle('show', totalItems === 0);
        pagination.style.display = totalItems > 0 ? 'flex' : 'none';

        prevBtn.disabled = currentPage <= 1;
        nextBtn.disabled = currentPage >= totalPages;
    }

    prevBtn.addEventListener('click', function () {
        currentPage -= 1;
        render();
    });

    nextBtn.addEventListener('click', function () {
        currentPage += 1;
        render();
    });

    searchInput.addEventListener('input', applyFilter);

    render();
}

document.addEventListener('DOMContentLoaded', renderProjects);
